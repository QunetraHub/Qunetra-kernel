#!/usr/bin/env python3
import argparse, base64, datetime, re, sys

def der_read(buf, pos):
	tag = buf[pos]; l = buf[pos + 1]; p = pos + 2
	if l & 0x80:
		n = l & 0x7f; l = int.from_bytes(buf[p:p + n], 'big'); p += n
	return tag, p, p + l, p + l

def parse_time(buf, pos):
	tag, s, e, nxt = der_read(buf, pos)
	t = buf[s:e].decode()
	if tag == 0x17:
		yy = int(t[:2]); year = 1900 + yy if yy >= 50 else 2000 + yy; t = t[2:]
	else:
		year = int(t[:4]); t = t[4:]
	return datetime.datetime(year, int(t[0:2]), int(t[2:4]), int(t[4:6]), int(t[6:8]), min(int(t[8:10]), 59)), nxt

OID_RSA = bytes.fromhex("2a864886f70d010101")
OID_EC = bytes.fromhex("2a8648ce3d0201")
OID_P256 = bytes.fromhex("2a8648ce3d030107")
OID_P384 = bytes.fromhex("2b81040022")
OID_CN = bytes.fromhex("550403")

def analyse(der):
	_, s, _, _ = der_read(der, 0)
	_, ts, te, _ = der_read(der, s)
	p = ts
	if der[p] == 0xa0: p = der_read(der, p)[3]
	p = der_read(der, p)[3]
	p = der_read(der, p)[3]
	p = der_read(der, p)[3]
	_, vs, ve, p = der_read(der, p)
	not_before, q = parse_time(der, vs); not_after, _ = parse_time(der, q)
	sub_start = p; _, ss, se, p = der_read(der, p); subject = der[sub_start:p]
	spki_start = p; _, ks, ke, p = der_read(der, p); spki = der[spki_start:p]
	cn = ""
	q = ss
	while q < se:
		_, rs, re_, q = der_read(der, q)
		_, as_, ae, _ = der_read(der, rs)
		_, os_, oe, nxt = der_read(der, as_)
		if der[os_:oe] == OID_CN:
			_, vs2, ve2, _ = der_read(der, nxt); cn = der[vs2:ve2].decode('utf-8', 'replace')
	_, as_, ae, nxt = der_read(der, ks)
	_, os_, oe, nxt2 = der_read(der, as_)
	oid = der[os_:oe]; usable = False; desc = "unsupported key"
	_, bs, be, _ = der_read(der, nxt)
	if oid == OID_RSA:
		_, ss2, se2, _ = der_read(der, bs + 1)
		_, ns, ne, _ = der_read(der, ss2)
		modulus = der[ns:ne].lstrip(b'\0'); bits = len(modulus) * 8 - (8 - modulus[0].bit_length())
		desc = "RSA %d" % bits; usable = bits >= 2048
	elif oid == OID_EC:
		_, cs, ce, _ = der_read(der, nxt2); curve = der[cs:ce]
		desc = "P-256" if curve == OID_P256 else "P-384" if curve == OID_P384 else "other curve"
		usable = curve in (OID_P256, OID_P384)
	return dict(subject=subject, spki=spki, not_after=not_after, not_before=not_before, cn=cn, key=desc, usable=usable)

def read_pem(path):
	text = open(path, 'r', errors='replace').read()
	return [base64.b64decode(b) for b in re.findall(r"-----BEGIN CERTIFICATE-----(.*?)-----END CERTIFICATE-----", text, re.S)
			for b in [re.sub(r"\s+", "", b)]]

def c_array(name, data):
	lines = [",".join("0x%02x" % b for b in data[i:i + 32]) for i in range(0, len(data), 32)]
	return "static const uint8 %s[%d]={\n\t%s\n};" % (name, len(data), ",\n\t".join(lines))

def main():
	ap = argparse.ArgumentParser(description="Build roots.c for Qunetra from a PEM bundle")
	ap.add_argument("--bundle", default="/etc/ssl/certs/ca-certificates.crt")
	ap.add_argument("-o", "--output", default="roots.c")
	ap.add_argument("--list", action="store_true", help="print the roots that are included / skipped")
	ap.add_argument("--now", help="date used for the expiry check, YYYYMMDD (default: today)")
	args = ap.parse_args()
	now = datetime.datetime.strptime(args.now, "%Y%m%d") if args.now else datetime.datetime.now(datetime.timezone.utc).replace(tzinfo=None)
	certs = read_pem(args.bundle)
	roots, seen, skipped = [], set(), []
	for der in certs:
		try: r = analyse(der)
		except Exception as e:
			skipped.append(("?", "unreadable: %s" % e)); continue
		if not r['usable']: skipped.append((r['cn'], r['key'])); continue
		if r['not_after'] < now: skipped.append((r['cn'], "expired")); continue
		key = (r['subject'], r['spki'])
		if key in seen: continue
		seen.add(key); roots.append(r)
	out = ["/* Generated by tools/make-roots.py from %s, %d trusted roots. Do not edit: run the tool again. */" % (args.bundle, len(roots)),
			'#include "../../utility/types.h"\n#include "x509.h"']
	for i, r in enumerate(roots):
		out.append("/* %s (%s) */" % (r['cn'].replace("*/", "*"), r['key']))
		out.append(c_array("subject%d" % i, r['subject'])); out.append(c_array("spki%d" % i, r['spki']))
	out.append("const x509Root x509Roots[]={\n" + "".join("\t{subject%d,sizeof(subject%d),spki%d,sizeof(spki%d)},\n" % (i, i, i, i) for i in range(len(roots))) + "\t{0,0,0,0}\n};")
	out.append("const uint16 x509RootCount=%d;\n" % len(roots))
	open(args.output, "w").write("\n".join(out))
	if args.list:
		for r in roots: print("  + %-60s %s" % (r['cn'], r['key']))
		for cn, why in skipped: print("  - %-60s skipped: %s" % (cn, why))
	print("%s: %d roots written (%d skipped)" % (args.output, len(roots), len(skipped)))

if __name__ == "__main__":
	main()
